import { describe, expect, it } from 'vitest';
import { 遷移する, type 操作 } from './transition';
import type { 画面状態, 問題 } from './types';
import { 乱数生成器 } from './testHelpers';

function 遷移(現: 画面状態, 操作: 操作): 画面状態 {
  return 遷移する(現, 操作, 乱数生成器(7));
}

function 選択を進める(問題: 問題, タイプ: 問題['正解'][number]): 画面状態 {
  return 遷移({ クイズ画面: { 問題, 選択中: [タイプ], 答え合わせ済: false } }, { 種類: '答え合わせ' });
}

/** みず×ばつぐんの共通fixture（問題） */
const みずの問題: 問題 = {
  お題: 'みず',
  効果: 2,
  正解: ['でんき', 'くさ'],
  選択肢: ['でんき', 'くさ', 'ほのお', 'ノーマル', 'かくとう', 'ひこう'],
};

describe('画面遷移（タイトル画面→クイズ画面→終了画面→タイトル画面）', () => {
  it('タイトル画面でスタートすると、クイズ画面で新しい問題が出題される', () => {
    const 次 = 遷移('タイトル画面', { 種類: 'スタート' });
    expect(次).not.toBe('タイトル画面');
    expect(次).not.toBe('終了画面');
    if (次 === 'タイトル画面' || 次 === '相性表画面' || 次 === '終了画面') return;
    expect(次.クイズ画面.選択中).toEqual([]);
    expect(次.クイズ画面.答え合わせ済).toBe(false);
    expect(次.クイズ画面.問題.選択肢).toHaveLength(6);
  });

  it('クイズ画面で選択を切り替えると選択中が更新される', () => {
    const 開始 = 遷移('タイトル画面', { 種類: 'スタート' });
    if (開始 === 'タイトル画面' || 開始 === '相性表画面' || 開始 === '終了画面') return;
    const 次 = 遷移(開始, { 種類: '選択を切り替え', タイプ: 'ほのお' });
    if (次 === 'タイトル画面' || 次 === '相性表画面' || 次 === '終了画面') return;
    expect(次.クイズ画面.選択中).toEqual(['ほのお']);
    const 戻す = 遷移(次, { 種類: '選択を切り替え', タイプ: 'ほのお' });
    if (戻す === 'タイトル画面' || 戻す === '相性表画面' || 戻す === '終了画面') return;
    expect(戻す.クイズ画面.選択中).toEqual([]);
  });

  it('答え合わせすると答え合わせ済になり、選択中は保持される', () => {
    const 答え合わせ後 = 選択を進める(みずの問題, 'でんき');
    expect(答え合わせ後).not.toBe('タイトル画面');
    if (答え合わせ後 === 'タイトル画面' || 答え合わせ後 === '相性表画面' || 答え合わせ後 === '終了画面') return;
    expect(答え合わせ後.クイズ画面.答え合わせ済).toBe(true);
    expect(答え合わせ後.クイズ画面.選択中).toEqual(['でんき']);
  });

  it('次の問題では直前の問題とお題×効果が重複せず、選択中が空に戻る', () => {
    const 答え合わせ後 = 選択を進める(みずの問題, 'でんき');
    if (答え合わせ後 === 'タイトル画面' || 答え合わせ後 === '相性表画面' || 答え合わせ後 === '終了画面') return;
    const 次 = 遷移(答え合わせ後, { 種類: '次の問題' });
    if (次 === 'タイトル画面' || 次 === '相性表画面' || 次 === '終了画面') return;
    expect(次.クイズ画面.答え合わせ済).toBe(false);
    expect(次.クイズ画面.選択中).toEqual([]);
    const 前 = 答え合わせ後.クイズ画面.問題;
    const 新しい問題 = 次.クイズ画面.問題;
    expect(前.お題 === 新しい問題.お題 && 前.効果 === 新しい問題.効果).toBe(false);
  });

  it('クイズ画面でやめると終了画面へ、タイトルへもどるとタイトル画面へ', () => {
    const 開始 = 遷移('タイトル画面', { 種類: 'スタート' });
    const 終了 = 遷移(開始, { 種類: 'やめる' });
    expect(終了).toBe('終了画面');
    expect(遷移(終了, { 種類: 'タイトルへもどる' })).toBe('タイトル画面');
  });

  it('その画面で行えない操作は状態を変えない', () => {
    // タイトル画面ではやめる・答え合わせは行えない
    expect(遷移('タイトル画面', { 種類: 'やめる' })).toBe('タイトル画面');
    expect(遷移('タイトル画面', { 種類: '答え合わせ' })).toBe('タイトル画面');
    expect(遷移('タイトル画面', { 種類: 'タイトルへもどる' })).toBe('タイトル画面');
    // 何も選んでいない状態での答え合わせ・答え合わせ前の次の問題は行えない
    const 開始 = 遷移('タイトル画面', { 種類: 'スタート' });
    if (開始 === 'タイトル画面' || 開始 === '相性表画面' || 開始 === '終了画面') return;
    expect(遷移(開始, { 種類: '答え合わせ' })).toEqual(開始);
    expect(遷移(開始, { 種類: '次の問題' })).toEqual(開始);
    // 終了画面では次の問題・スタートは行えない
    expect(遷移('終了画面', { 種類: '次の問題' })).toBe('終了画面');
    expect(遷移('終了画面', { 種類: 'スタート' })).toBe('終了画面');
    // 答え合わせ済のあとの選択の切り替えは行えない
    const 答え合わせ後 = 選択を進める(みずの問題, 'でんき');
    expect(遷移(答え合わせ後, { 種類: '選択を切り替え', タイプ: 'ほのお' })).toEqual(答え合わせ後);
  });
});

describe('画面遷移（タイトル画面→相性表画面→タイトル画面）', () => {
  it('タイトル画面で相性表をみると相性表画面へ遷移する', () => {
    expect(遷移('タイトル画面', { 種類: '相性表をみる' })).toBe('相性表画面');
  });

  it('相性表画面でタイトルへもどるとタイトル画面へ戻る', () => {
    expect(遷移('相性表画面', { 種類: 'タイトルへもどる' })).toBe('タイトル画面');
  });

  it('その画面で行えない操作は状態を変えない', () => {
    // 相性表画面ではスタート・やめる・次の問題・選択の切り替えは行えない
    expect(遷移('相性表画面', { 種類: 'スタート' })).toBe('相性表画面');
    expect(遷移('相性表画面', { 種類: 'やめる' })).toBe('相性表画面');
    expect(遷移('相性表画面', { 種類: '次の問題' })).toBe('相性表画面');
    expect(遷移('相性表画面', { 種類: '選択を切り替え', タイプ: 'ほのお' })).toBe('相性表画面');
    expect(遷移('相性表画面', { 種類: '答え合わせ' })).toBe('相性表画面');
    // 相性表画面でさらに相性表をみることはできない
    expect(遷移('相性表画面', { 種類: '相性表をみる' })).toBe('相性表画面');
    // クイズ画面・終了画面では相性表をみることはできない
    const 開始 = 遷移('タイトル画面', { 種類: 'スタート' });
    if (開始 === 'タイトル画面' || 開始 === '相性表画面' || 開始 === '終了画面') return;
    expect(遷移(開始, { 種類: '相性表をみる' })).toEqual(開始);
    expect(遷移('終了画面', { 種類: '相性表をみる' })).toBe('終了画面');
  });
});
