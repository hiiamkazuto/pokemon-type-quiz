import type { 画面状態, タイプ, 問題 } from './types';
import { 問題を生成する } from './generator';

/** 画面への操作。画面はURLルーティングではなくアプリ内の状態遷移で切り替える（ADR 0001） */
export type 操作 =
  | { 種類: 'スタート' }
  | { 種類: '相性表をみる' }
  | { 種類: '選択を切り替え'; タイプ: タイプ }
  | { 種類: '答え合わせ' }
  | { 種類: '次の問題' }
  | { 種類: 'やめる' }
  | { 種類: 'タイトルへもどる' };

/** 現がクイズ画面のときだけその状態を取り出す。タイトル画面・終了画面では null */
function クイズ画面を取り出す(現: 画面状態): { 問題: 問題; 選択中: タイプ[]; 答え合わせ済: boolean } | null {
  return 現 === 'タイトル画面' || 現 === '相性表画面' || 現 === '終了画面' ? null : 現.クイズ画面;
}

/** 現在の画面状態に操作を適用して次の画面状態を返す。その画面で行えない操作は状態を変えずに返す */
export function 遷移する(現: 画面状態, 操作: 操作, 乱数: () => number = Math.random): 画面状態 {
  switch (操作.種類) {
    case 'スタート':
      return 現 === 'タイトル画面'
        ? { クイズ画面: { 問題: 問題を生成する(undefined, 乱数), 選択中: [], 答え合わせ済: false } }
        : 現;
    case '選択を切り替え': {
      const クイズ = クイズ画面を取り出す(現);
      if (!クイズ || クイズ.答え合わせ済) return 現;
      const 選択中 = クイズ.選択中.includes(操作.タイプ)
        ? クイズ.選択中.filter((t) => t !== 操作.タイプ)
        : [...クイズ.選択中, 操作.タイプ];
      return { クイズ画面: { ...クイズ, 選択中 } };
    }
    case '答え合わせ': {
      const クイズ = クイズ画面を取り出す(現);
      if (!クイズ || クイズ.答え合わせ済 || クイズ.選択中.length === 0) return 現;
      return { クイズ画面: { ...クイズ, 答え合わせ済: true } };
    }
    case '次の問題': {
      const クイズ = クイズ画面を取り出す(現);
      if (!クイズ || !クイズ.答え合わせ済) return 現;
      return {
        クイズ画面: {
          問題: 問題を生成する(クイズ.問題, 乱数),
          選択中: [],
          答え合わせ済: false,
        },
      };
    }
    case '相性表をみる':
      return 現 === 'タイトル画面' ? '相性表画面' : 現;
    case 'やめる':
      return クイズ画面を取り出す(現) !== null ? '終了画面' : 現;
    case 'タイトルへもどる':
      return 現 === '終了画面' || 現 === '相性表画面' ? 'タイトル画面' : 現;
  }
}
