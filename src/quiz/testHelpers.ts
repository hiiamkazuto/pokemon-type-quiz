/** 同じ値を繰り返す疑似乱数（線形合同法）。テストを再現可能にする */
export function 乱数生成器(シード: number): () => number {
  let 状態 = シード;
  return () => {
    状態 = (状態 * 1103515245 + 12345) % 2147483648;
    return 状態 / 2147483648;
  };
}
