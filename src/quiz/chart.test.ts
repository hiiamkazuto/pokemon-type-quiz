import { describe, expect, it } from 'vitest';
import { 効果を参照する } from './chart';
import { 全タイプ } from './types';

describe('効果を参照する（第9世代相性表）', () => {
  it('ばつぐんの既知の組合せで2を返す', () => {
    expect(効果を参照する('みず', 'ほのお')).toBe(2);
    expect(効果を参照する('でんき', 'みず')).toBe(2);
    expect(効果を参照する('かくとう', 'はがね')).toBe(2);
    expect(効果を参照する('じめん', 'でんき')).toBe(2);
    expect(効果を参照する('いわ', 'むし')).toBe(2);
    expect(効果を参照する('フェアリー', 'あく')).toBe(2);
  });

  it('いまひとつの既知の組合せで0.5を返す', () => {
    expect(効果を参照する('ほのお', 'みず')).toBe(0.5);
    expect(効果を参照する('フェアリー', 'どく')).toBe(0.5);
    expect(効果を参照する('はがね', 'でんき')).toBe(0.5);
    expect(効果を参照する('むし', 'フェアリー')).toBe(0.5);
  });

  it('こうかなしの既知の組合せで0を返す', () => {
    expect(効果を参照する('でんき', 'じめん')).toBe(0);
    expect(効果を参照する('エスパー', 'あく')).toBe(0);
    expect(効果を参照する('ゴースト', 'ノーマル')).toBe(0);
    expect(効果を参照する('じめん', 'ひこう')).toBe(0);
    expect(効果を参照する('ドラゴン', 'フェアリー')).toBe(0);
    expect(効果を参照する('どく', 'はがね')).toBe(0);
  });

  it('相性表に非記載の組合せはこうかあり（1倍）を返す', () => {
    expect(効果を参照する('ノーマル', 'ほのお')).toBe(1);
    expect(効果を参照する('ひこう', 'ひこう')).toBe(1);
    expect(効果を参照する('ドラゴン', 'みず')).toBe(1);
  });

  it('18×18のすべての組合せで効果が定義域内に収まる', () => {
    for (const 攻める側 of 全タイプ) {
      for (const 守る側 of 全タイプ) {
        const 倍率 = 効果を参照する(攻める側, 守る側);
        expect([2, 1, 0.5, 0]).toContain(倍率);
      }
    }
  });

  it('第9世代の既知の耐性構造を満たす（ノーマルの特殊・はがねのばつぐん受けるなど）', () => {
    // 第6世代以降: あく・ゴーストがはがねにいまひとつにならない
    expect(効果を参照する('あく', 'はがね')).toBe(1);
    expect(効果を参照する('ゴースト', 'はがね')).toBe(1);
    // 第9世代: どく・こおりでフェアリーはばつぐん／いまひとつ
    expect(効果を参照する('どく', 'フェアリー')).toBe(2);
    expect(効果を参照する('こおり', 'フェアリー')).toBe(1);
    // 自分と同じタイプは原則いまひとつ（ドラゴンはばつぐん）
    expect(効果を参照する('ほのお', 'ほのお')).toBe(0.5);
    expect(効果を参照する('ドラゴン', 'ドラゴン')).toBe(2);
  });
});
